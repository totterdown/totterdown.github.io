def guide_cards(indent='        '):
    return '\n'.join(f'{indent}<a href="{h}"><strong>{t}</strong><span>{s}</span></a>' for h, t, s in GUIDES)


def terrace(cls='terrace'):
    """An inline SVG row of coloured terraced houses stepping up a hill."""
    colours = ['#e76f51', '#f4a261', '#e9c46a', '#8ab17d', '#2a9d8f', '#4f7cac', '#8e7dbe', '#f28482', '#e76f51', '#f4a261']
    w, gap = 64, 0
    parts = []
    for i, c in enumerate(colours):
        x = i * (w + gap)
        base = 178 - i * 7  # each house a little higher up the hill
        top = base - 92
        parts.append(f'<rect x="{x}" y="{top}" width="{w}" height="{200 - top}" fill="{c}"/>')
        parts.append(f'<rect x="{x}" y="{top - 6}" width="{w}" height="8" fill="#1d2433" opacity=".18"/>')
        parts.append(f'<rect x="{x + 10}" y="{top + 14}" width="16" height="22" rx="2" fill="#fffaf2" opacity=".9"/>')
        parts.append(f'<rect x="{x + 38}" y="{top + 14}" width="16" height="22" rx="2" fill="#fffaf2" opacity=".9"/>')
        parts.append(f'<rect x="{x + 10}" y="{top + 50}" width="16" height="22" rx="2" fill="#fffaf2" opacity=".9"/>')
        parts.append(f'<path d="M{x + 38} {top + 76}v-20a8 8 0 0 1 16 0v20z" fill="#1d2433" opacity=".55"/>')
        parts.append(f'<rect x="{x + 22}" y="{top - 16}" width="8" height="12" fill="#1d2433" opacity=".35"/>')
    parts.append('<path d="M0 170 L640 107 L640 200 L0 200z" fill="#1d2433" opacity=".08"/>')
    return (f'<svg class="{cls}" viewBox="0 0 640 200" preserveAspectRatio="xMidYMax slice" aria-hidden="true" focusable="false">'
            + ''.join(parts) + '</svg>')


def page(slug, title, desc, og_desc, crumb, h1, published, modified, body, source, extra_graph=None):
    """A guide page: Article and BreadcrumbList data, quick answer, sources list."""
    url = url_for(slug)
    body, lis = cite(body)
    graph = [
        {'@type': 'Article', '@id': f'{url}#article', 'headline': title, 'description': desc,
         'datePublished': published, 'dateModified': modified, 'inLanguage': 'en-GB',
         'image': f'{SITE}/img/og.png', 'mainEntityOfPage': url,
         'author': {'@id': f'{SITE}/#organization'}, 'publisher': ORG,
         'isPartOf': {'@type': 'WebSite', '@id': f'{SITE}/#website', 'name': NAME, 'url': f'{SITE}/'}},
        {'@type': 'BreadcrumbList', 'itemListElement': [
            {'@type': 'ListItem', 'position': 1, 'name': NAME, 'item': f'{SITE}/'},
            {'@type': 'ListItem', 'position': 2, 'name': crumb, 'item': url}]},
    ] + (extra_graph or [])
    sources = ''
    if lis:
        sources = f'''
    <h2 id="sources">Sources</h2>
    <ol class="sources">
{lis}
    </ol>
'''
    return head(title, desc, slug, og_desc, graph=graph, source=source) + f'''<body>
{topbar('/' + slug + '/')}
  <main class="doc">
    <nav class="crumbs" aria-label="Breadcrumb"><a href="/">Home</a> / {crumb}</nav>

    <h1>{h1}</h1>
{body.rstrip()}
{sources}
    <aside class="forsale-strip"><a href="/domain-for-sale/">Totterdown.com is for sale</a></aside>
  </main>

{footer()}</body>
</html>
'''


def plain(slug, title, desc, h1, modified, body, source, robots='index, follow', og_desc=None, graph=None):
    """About, privacy and other plain pages."""
    body, lis = cite(body)
    sources = ''
    if lis:
        sources = f'''
    <h2 id="sources">Sources</h2>
    <ol class="sources">
{lis}
    </ol>
'''
    return head(title, desc, slug, og_desc, og_type='website', robots=robots, graph=graph, source=source) + f'''<body>
{topbar('/' + slug + '/')}
  <main class="doc">
    <h1>{h1}</h1>
    <p class="meta">Updated {long_date(modified)}</p>
{body.rstrip()}
{sources}  </main>

{footer()}</body>
</html>
'''
